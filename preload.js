'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('widget', {
  getState: () => ipcRenderer.invoke('get-state'),
  onUsage: (cb) => ipcRenderer.on('usage', (_e, payload) => cb(payload)),
  onTheme: (cb) => ipcRenderer.on('theme', (_e, theme) => cb(theme)),
  onFade: (cb) => ipcRenderer.on('fade', (_e, mode) => cb(mode)),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, update) => cb(update)),
  installUpdate: () => ipcRenderer.send('install-update'),
  onOpenPanel: (cb) => ipcRenderer.on('open-panel', () => cb()),
  onForceCollapse: (cb) => ipcRenderer.on('force-collapse', () => cb()),
  onShown: (cb) => ipcRenderer.on('shown', () => cb()),
  refresh: () => ipcRenderer.send('refresh'),
  setTheme: (theme) => ipcRenderer.send('set-theme', theme),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  setSetting: (key, value) => ipcRenderer.invoke('set-setting', key, value),
  checkUpdate: () => ipcRenderer.send('check-update'),
  openRaw: () => ipcRenderer.send('open-raw'),
  openLogCheck: () => ipcRenderer.send('open-logcheck'),
  projects: (sinceMs, bucket) => ipcRenderer.invoke('projects', sinceMs, bucket),
  history: (sinceMs) => ipcRenderer.invoke('history', sinceMs),
  patterns: () => ipcRenderer.invoke('patterns'),
  productUsage: (sinceMs, bucket) => ipcRenderer.invoke('product-usage', sinceMs, bucket),
  expand: () => ipcRenderer.send('expand'),
  collapse: () => ipcRenderer.send('collapse'),
  hide: () => ipcRenderer.send('hide'),
  quit: () => ipcRenderer.send('quit'),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragMove: () => ipcRenderer.send('drag-move'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  resizeStart: (corner) => ipcRenderer.send('resize-start', corner),
  resizeMove: () => ipcRenderer.send('resize-move'),
  resizeEnd: () => ipcRenderer.send('resize-end'),
  contextMenu: () => ipcRenderer.send('context-menu'),
  ackNews: (keys) => ipcRenderer.send('ack-news', keys),
  testNotification: () => ipcRenderer.invoke('test-notification'),
  setShortcut: (keyInfo) => ipcRenderer.invoke('set-shortcut', keyInfo),
  pauseShortcut: (paused) => ipcRenderer.send('pause-shortcut', paused),
  exportReport: (kind) => ipcRenderer.invoke('export', kind),
  copyText: (text) => ipcRenderer.invoke('copy-text', text),
  openLink: (url) => ipcRenderer.send('open-link', url),
});
